"""Authenticated, server-side connection to the user's Google Apps Script bridge."""
from __future__ import annotations

import json
import os
import re
import urllib.request
from pathlib import Path

CONFIG_PATH = Path("config/google_bridge.json")
URL_RE = re.compile(r"https://script\.google\.com/macros/s/[A-Za-z0-9_-]+/exec\Z")


def save_bridge_config(url: str, token: str) -> None:
    url, token = url.strip(), token.strip()
    if not URL_RE.fullmatch(url):
        raise ValueError("Use the deployed Apps Script web app URL ending in /exec")
    if len(token) < 32:
        raise ValueError("Use the connection key generated by the Google setup menu")
    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    temporary = CONFIG_PATH.with_suffix('.tmp')
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, 'w', encoding='utf-8') as file:
        json.dump({"url": url, "token": token}, file)
    os.replace(temporary, CONFIG_PATH)


class GoogleBridge:
    def __init__(self):
        if not CONFIG_PATH.exists():
            raise RuntimeError("Connect Google in the dashboard first. See the Google setup guide.")
        self.config = json.loads(CONFIG_PATH.read_text(encoding='utf-8'))
        if not URL_RE.fullmatch(self.config.get('url', '')):
            raise ValueError('Invalid Google bridge URL')

    def call(self, action: str, **payload) -> dict:
        request = urllib.request.Request(self.config['url'],
            data=json.dumps({"token": self.config['token'], "action": action, **payload}).encode(),
            headers={"Content-Type": "application/json"}, method='POST')
        try:
            with urllib.request.urlopen(request, timeout=90) as response:
                data = json.loads(response.read(8 * 1024 * 1024))
        except json.JSONDecodeError as exc:
            raise RuntimeError("Google returned a sign-in page instead of data. Check the web app deployment access.") from exc
        except OSError as exc:
            raise RuntimeError("Google could not be reached. Your game is saved locally; reconnect the Pi to internet and retry.") from exc
        if not data.get('ok'):
            raise RuntimeError(data.get('error', 'Google sync failed'))
        return data
